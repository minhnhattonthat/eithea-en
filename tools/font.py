ALIAS = {'♪': '{', '♥': '}', '…': None}  # Unicode -> slot char; '…' is rejected (write "...")
CHARS = {chr(0x20 + i) for i in range(94)} - {'{', '}'} | set(ALIAS) - {'…'}


def half(ch):
    """24 bytes: plane0 rows 0-11 then plane1 rows 0-11, 1 byte per row, pixels in bits 7..3."""
    rows = [""] + G.get(ch, "").split("/") if G.get(ch) else [""]
    rows = (rows + [""] * 12)[:12]
    bs = bytes(sum(0x80 >> x for x, c in enumerate(r) if c == "#") for r in rows)
    return bs + bs


def slot(c):
    """character -> index 0..93 (ASCII 0x20..0x7D)."""
    c = ALIAS.get(c, c) if c in ALIAS else c
    if c is None or not (0x20 <= ord(c) <= 0x7D):
        raise ValueError(f"no glyph for {c!r}")
    return ord(c) - 0x20


def pair(a, b):
    i1, i2 = slot(a), slot(b)
    t = (i1 & 1) * 94 + i2
    lead, trail = 0x88 + (i1 >> 1), 0x40 + t
    lead += 0x40 if lead > 0x9F else 0
    trail += 1 if trail >= 0x7F else 0
    return bytes((lead, trail))


def unpair(lead, trail):
    t = trail - 0x40 - (trail >= 0x80)
    l = lead - 0x88 - (0x40 if lead >= 0xE0 else 0)
    i1, i2 = 2 * l + (t >= 94), t % 94
    rev = {v: k for k, v in ALIAS.items() if v}
    return "".join(rev.get(chr(0x20 + i), chr(0x20 + i)) for i in (i1, i2))


def encode(text):
    """ASCII text -> pair codes; odd length gets a trailing space."""
    if len(text) % 2:
        text += " "
    return b"".join(pair(text[i], text[i + 1]) for i in range(0, len(text), 2))


def build(out):
    out = pathlib.Path(out)
    out.mkdir(parents=True, exist_ok=True)
    # patches out/EITHEA.EXE (a fresh copy of the original) and writes the ext code
    (out / "EITHEA.EXE").write_bytes((root / "work/d1/tree/EITHEA.EXE").read_bytes())
    subprocess.run([str(root / "tools/armips/armips.exe"), str(root / "asm/font.asm"), "-root", str(out),
                    "-strequ", "CODEOUT", "fontext.bin"], check=True)
    ext = (out / "fontext.bin").read_bytes()
    order = [chr(0x20 + i) for i in range(94)]
    rev = {v: k for k, v in ALIAS.items() if v}
    hw = b"".join(half(rev.get(c, c)) for c in order) + bytes(24 * (NCH - 94))
    head = hw + bytes(48) + ext
    head += bytes(-len(head) % 48)
    n = len(head) // 48
    bl = (ORIG / "0931_KANJI.BL").read_bytes()
    inn = (ORIG / "0930_KANJI.IN").read_bytes()
    assert len(head) == CODEOFF + len(ext) + (-(CODEOFF + len(ext)) % 48)
    (out / "KANJI.BL").write_bytes(DUMMY * n + bl)
    (out / "KANJI.IN").write_bytes(head + inn)
    assert len(DUMMY * n + bl) <= 0x1000 and len(head + inn) <= 0x15800, "font buffers overflow"
    return out / "KANJI.IN", out / "KANJI.BL"


def preview(png, text="The quick brown fox jumps over the lazy dog! 0123456789 ?.,;:'\"()[]-+=/&%$#@*<>_^|\\`~ ♪♥"):
    from PIL import Image
    text = text.replace("~", "")
    w = 6 * len(text)
    im = Image.new("L", (w, 12))
    for k, c in enumerate(text):
        d = half(c)
        for r in range(12):
            for x in range(6):
                if d[r] & (0x80 >> x):
                    im.putpixel((6 * k + x, r), 255)
    im.resize((w * 4, 48), Image.NEAREST).save(png)


